package nfarts

import java.nio.file.Paths

import spock.lang.Specification

class TitleTest extends Specification {

    def 'should read the pipeline and revision from a command line' () {
        expect:
        Title.fromCommand(command, 'happy_turing') == new Title(pipeline, revision, 'happy_turing')
        where:
        command                                                                   | pipeline         | revision
        'nextflow run nf-core/rnavar -r 1.3.0 -profile test,docker --outdir res' | 'nf-core/rnavar' | '1.3.0'
        'nextflow run -profile test nf-core/sarek'                                | 'nf-core/sarek'  | null
        'nextflow -q run validation/ -plugins nf-arts@0.1.0'                      | 'validation/'    | null
        'nextflow info'                                                           | null             | null
        null                                                                      | null             | null
    }

    def 'should join the parts it has' () {
        expect:
        new Title('nf-core/rnavar', '1.3.0', 'happy_turing').text() == 'nf-core/rnavar · 1.3.0 · happy_turing'
        new Title('nf-core/rnavar', null, 'happy_turing').text() == 'nf-core/rnavar · happy_turing'
        new Title(null, null, null).text() == ''
    }

    def 'should read the title and session from an execution report' () {
        given:
        def trace = Paths.get(TitleTest.getResource('/execution_trace.txt').toURI())

        when:
        def report = RunReader.report(trace)
        then:
        report.title() == new Title('nf-core/rnavar', '1.2.2', 'exotic_kimura')
        report.session() == UUID.fromString('1ba77276-0c91-46e0-862d-e017d222de42')

        expect:
        RunReader.report(trace.resolveSibling('missing_trace.txt')) == null
    }

    def 'should fall back to the command line of a report without repository' () {
        given:
        def html = '''<title>[sad_curie] Nextflow Workflow Report</title>
            <dd><pre class="nfcommand"><code>nextflow run main.nf -profile test</code></pre></dd>'''

        expect:
        Report.parse(html) == new Report(new Title('main.nf', null, 'sad_curie'), null)
        Report.parse('<html></html>') == new Report(new Title(null, null, null), null)
    }

    def 'should draw the caption under the artwork' () {
        given:
        def tiles = SyntheticRun.create(1, 4)
        def title = new Title('nf-core/a&b', '1.0', 'happy_turing')

        when:
        def svg = new String(Artist.paint(tiles, new ArtsConfig(width: 400, height: 400), 'svg', 1, title))
        then:
        svg.contains('>nf-core/a&amp;b · 1.0 · happy_turing</text>')
        Artist.VERSION ==~ /\d+\.\d+\.\d+.*/
        svg.contains(">generated by nf-arts v${Artist.VERSION}</text>")

        expect:
        !new String(Artist.paint(tiles, new ArtsConfig(title: false), 'svg', 1, title)).contains('<text')
        new String(Artist.paint(tiles, new ArtsConfig([:]), 'svg', 1, null)).count('<text') == 1
    }
}
