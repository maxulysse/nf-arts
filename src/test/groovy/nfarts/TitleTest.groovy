package nfarts

import java.nio.file.Paths

import spock.lang.Specification

class TitleTest extends Specification {

    def 'should read the pipeline and revision from a command line' () {
        expect:
        Title.fromCommand(command, 'happy_turing') == new Title(pipeline, revision, 'happy_turing')
        where:
        command                                                                   | pipeline         | revision
        'nextflow run nf-core/rnavar -r 1.3.0 -profile test,docker --outdir res' | 'nf-core/rnavar' | '1.3.0'
        'nextflow run -profile test nf-core/sarek'                                | 'nf-core/sarek'  | null
        'nextflow -q run nf-core/sarek -plugins nf-arts@0.1.0'                    | 'nf-core/sarek'  | null
        'nextflow run /home/me/secret/main.nf -r dev'                             | null             | 'dev'
        'nextflow info'                                                           | null             | null
        null                                                                      | null             | null
    }

    def 'should join the parts it has' () {
        expect:
        new Title('nf-core/rnavar', '1.3.0', 'happy_turing').text() == 'nf-core/rnavar · 1.3.0 · happy_turing'
        new Title('nf-core/rnavar', null, 'happy_turing').text() == 'nf-core/rnavar · happy_turing'
        new Title(null, null, null).text() == ''
    }

    def 'should read the title and session from an execution report' () {
        given:
        def trace = Paths.get(TitleTest.getResource('/execution_trace.txt').toURI())

        when:
        def report = RunReader.report(trace)
        then:
        report.title() == new Title('nf-core/rnavar', '1.2.2', 'exotic_kimura')
        report.session() == UUID.fromString('1ba77276-0c91-46e0-862d-e017d222de42')

        expect:
        RunReader.report(trace.resolveSibling('missing_trace.txt')) == null
    }

    def 'should fall back to the command line of a report without repository' () {
        given:
        def html = '''<title>[sad_curie] Nextflow Workflow Report</title>
            <dd><pre class="nfcommand"><code>nextflow run main.nf -profile test</code></pre></dd>'''

        expect:
        Report.parse(html) == new Report(new Title(null, null, 'sad_curie'), null)
        Report.parse(html.replace('main.nf', 'nf-core/sarek')) == new Report(new Title('nf-core/sarek', null, 'sad_curie'), null)
        Report.parse('<html></html>') == new Report(new Title(null, null, null), null)
    }

    def 'should drop a null revision from a report' () {
        given:
        def html = '''<title>[zen_picasso] Nextflow Workflow Report</title>
            <dt class="col-sm-3">Workflow repository</dt>
            <dd class="col-sm-9"><code>https://github.com/nf-core/raredisease</code>, revision <code>REVISION</code> (commit hash <code>47a41a5</code>)</dd>'''

        expect:
        Report.parse(html.replace('REVISION', 'null')).title() == new Title('nf-core/raredisease', null, 'zen_picasso')
        Report.parse(html.replace('REVISION', '2.3.0')).title() == new Title('nf-core/raredisease', '2.3.0', 'zen_picasso')
    }

    def 'should draw the caption under the artwork' () {
        given:
        def tiles = SyntheticRun.create(1, 4)
        def title = new Title('nf-core/a&b', '1.0', 'happy_turing')

        when:
        def svg = SyntheticRun.svg(tiles, new ArtsConfig(width: 400, height: 400), 1, title)
        then:
        svg.contains('>nf-core/a&amp;b · 1.0 · happy_turing</text>')
        Artist.VERSION ==~ /\d+\.\d+\.\d+.*/
        svg.contains(">generated by nf-arts v${Artist.VERSION}</text>")

        expect:
        !SyntheticRun.svg(tiles, new ArtsConfig(title: false), 1, title).contains('<text')
        SyntheticRun.svg(tiles, new ArtsConfig([:])).count('<text') == 1
    }

    def 'should keep only pipelines that are not local paths' () {
        expect:
        Title.shareable(pipeline) == shown
        where:
        pipeline                                | shown
        'nf-core/rnavar'                        | 'nf-core/rnavar'
        'https://github.com/nf-core/rnavar'     | 'https://github.com/nf-core/rnavar'
        'https://user:token@github.com/a/b'     | null
        'git@github.com:nf-core/rnavar.git'     | null
        'main.nf'                               | null
        'rnavar'                                | null
        './main.nf'                             | null
        '../rnavar/main.nf'                     | null
        'validation/'                           | null
        '/home/me/secret-project/main.nf'       | null
        '~/pipelines/main.nf'                   | null
        'a/b/main.nf'                           | null
        null                                    | null
    }

    def 'should find the pipeline among run options' () {
        expect:
        Title.fromCommand(command, null).pipeline() == pipeline
        where:
        command                                                                    | pipeline
        'nextflow run -resume nf-core/rnavar'                                      | 'nf-core/rnavar'
        'nextflow run -resume last nf-core/rnavar'                                 | 'nf-core/rnavar'
        'nextflow run -resume 1ba77276-0c91-46e0-862d-e017d222de42 nf-core/rnavar' | 'nf-core/rnavar'
        'nextflow run --input samples.csv nf-core/rnavar'                          | 'nf-core/rnavar'
        'nextflow run --input=samples.csv nf-core/rnavar'                          | 'nf-core/rnavar'
        'nextflow run -bg -latest -with-report -c x.config nf-core/sarek'          | 'nf-core/sarek'
        'nextflow run -revision dev -profile test nf-core/sarek'                   | 'nf-core/sarek'
        'nextflow run nf-core/rnavar -resume --outdir results'                     | 'nf-core/rnavar'
        'nextflow run -with-trace /home/me/trace.txt nf-core/rnavar'               | 'nf-core/rnavar'
        'nextflow run -with-report report.html -with-dag dag.png nf-core/rnavar'   | 'nf-core/rnavar'
        'nextflow run -with-docker my/image nf-core/rnavar'                        | 'nf-core/rnavar'
        'nextflow run -output-dir /home/me/out -lib lib nf-core/rnavar'            | 'nf-core/rnavar'
        'nextflow run -process.cpus 2 nf-core/rnavar'                              | 'nf-core/rnavar'
        'nextflow run -process.cpus=2 nf-core/rnavar'                              | 'nf-core/rnavar'
        'nextflow run -with-tower -c x.config nf-core/rnavar'                      | 'nf-core/rnavar'
        'nextflow run -ansi-log -c x.config nf-core/rnavar'                        | 'nf-core/rnavar'
    }
}
