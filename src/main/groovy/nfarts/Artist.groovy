package nfarts

import java.nio.file.Files
import java.nio.file.Path

import groovy.transform.CompileStatic
import groovy.util.logging.Slf4j
import nextflow.file.FileHelper

/**
 * Paints a run with the configured style, palette and size.
 */
// Nextflow's console only shows loggers under `nextflow`
@Slf4j(category = 'nextflow.arts')
@CompileStatic
class Artist {

    static final Map<String, Style> STYLES = [
        radial     : new RadialStyle(),
        hilbert    : new HilbertStyle(),
        ridgeline  : new RidgelineStyle(),
        phyllotaxis: new PhyllotaxisStyle(),
        flowfield  : new FlowFieldStyle(),
        mondrian   : new MondrianStyle(),
        tree       : new TreeStyle(),
        ginkgo     : new GinkgoStyle(),
        iris       : new IrisStyle(),
        butterfly  : new ButterflyStyle(),
    ] as Map<String, Style>

    static final String VERSION = version()

    private static String version() {
        final props = new Properties()
        Artist.getResourceAsStream('/nf-arts.properties')?.withCloseable { InputStream it -> props.load(it) }
        return props.getProperty('version')
    }

    /** paint the run to `arts.file`, or to `art-<runName>.svg` and `.png` */
    static List<Path> save(PaintedRun run, ArtsConfig config, Closure warn = { log.warn(it as String) }) {
        write(run, config, outputPaths(run, config), warn)
    }

    /** a failed file does not stop the others; fails only if no file was written */
    static List<Path> write(PaintedRun run, ArtsConfig config, List<Path> paths, Closure warn) {
        final written = [] as List<Path>
        Throwable failure = null
        for( path in paths ) {
            try {
                final bytes = paint(run, config, ArtsConfig.format(path.toString()))
                if( path.parent )
                    Files.createDirectories(path.parent)
                Files.write(path, bytes)
                written << path
            }
            catch( Throwable e ) {
                failure = e
                warn.call("nf-arts: unable to write ${path} -- ${e.message}".toString())
            }
        }
        if( !written )
            throw failure
        return written
    }

    static List<Path> outputPaths(PaintedRun run, ArtsConfig config) {
        final name = "art-${run.title().runName() ?: 'run'}"
        final files = config.file ? [config.file] : ["${name}.svg".toString(), "${name}.png".toString()]
        files.collect { String it -> FileHelper.asPath(it) }
    }

    static byte[] paint(PaintedRun run, ArtsConfig config, String format) {
        final palette = Palette.of(config.palette, config.colors, config.background)
        final Canvas canvas = format == 'png'
            ? new PngCanvas(config.width, config.height, palette.background)
            : new SvgCanvas(config.width, config.height, palette.background)
        final style = STYLES[config.style]
        // caption band at the bottom, the artwork above it
        final band = config.title ? (int) Math.round(Math.min(config.width, config.height) * 0.1d) : 0
        // mix the seed: java.util.Random gives near-identical first draws for nearby seeds
        style.draw(new Run(run.tiles()), band ? new InsetCanvas(canvas, config.height - band) : canvas, palette, new Random(run.seed() * 0x9E3779B97F4A7C15L))
        if( band ) {
            final text = run.title().text()
            if( text )
                canvas.text(config.width / 2d, config.height - band * 0.5d, text, band * 0.28d, palette.ink(), 0.9d)
            canvas.text(config.width / 2d, config.height - band * 0.18d, "generated by nf-arts${VERSION ? " v${VERSION}" : ''}".toString(), band * 0.14d, palette.ink(), 0.6d)
        }
        return canvas.bytes()
    }
}
