package nfarts

import java.nio.file.Files
import java.nio.file.Path

import groovy.transform.CompileStatic
import nextflow.file.FileHelper

/**
 * Paints a run with the configured style, palette and size.
 */
@CompileStatic
class Artist {

    static final Map<String, Style> STYLES = [
        radial     : new RadialStyle(),
        hilbert    : new HilbertStyle(),
        ridgeline  : new RidgelineStyle(),
        phyllotaxis: new PhyllotaxisStyle(),
        flowfield  : new FlowFieldStyle(),
        mondrian   : new MondrianStyle(),
        tree       : new TreeStyle(),
        ginkgo     : new GinkgoStyle(),
        iris       : new IrisStyle(),
    ] as Map<String, Style>

    static final String VERSION = version()

    private static String version() {
        final props = new Properties()
        Artist.getResourceAsStream('/nf-arts.properties')?.withCloseable { InputStream it -> props.load(it) }
        return props.getProperty('version')
    }

    /** paint the run to `arts.file`, or `art-<runName>.svg` */
    static Path save(PaintedRun run, ArtsConfig config) {
        final path = outputPath(run, config)
        final bytes = paint(run.tiles(), config, ArtsConfig.format(path.toString()), run.seed(), run.title())
        if( path.parent )
            Files.createDirectories(path.parent)
        Files.write(path, bytes)
        return path
    }

    static Path outputPath(PaintedRun run, ArtsConfig config) {
        FileHelper.asPath(config.file ?: "art-${run.title().runName() ?: 'run'}.svg".toString())
    }

    static byte[] paint(List<TaskTile> tiles, ArtsConfig config, String format, long seed, Title title = null) {
        final palette = Palette.of(config.palette, config.colors, config.background)
        final Canvas canvas = format == 'png'
            ? new PngCanvas(config.width, config.height, palette.background)
            : new SvgCanvas(config.width, config.height, palette.background)
        final style = STYLES[config.style]
        // caption band at the bottom, the artwork above it
        final band = config.title ? (int) Math.round(Math.min(config.width, config.height) * 0.1d) : 0
        // mix the seed: java.util.Random gives near-identical first draws for nearby seeds
        if( tiles )
            style.draw(new Run(tiles), band ? new InsetCanvas(canvas, config.height - band) : canvas, palette, new Random(seed * 0x9E3779B97F4A7C15L))
        if( band ) {
            final text = title?.text()
            if( text )
                canvas.text(config.width / 2d, config.height - band * 0.5d, text, band * 0.28d, palette.ink(), 0.9d)
            canvas.text(config.width / 2d, config.height - band * 0.18d, "generated by nf-arts${VERSION ? " v${VERSION}" : ''}".toString(), band * 0.14d, palette.ink(), 0.6d)
        }
        return canvas.bytes()
    }
}
