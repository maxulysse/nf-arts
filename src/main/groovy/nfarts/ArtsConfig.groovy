package nfarts

import groovy.transform.CompileStatic
import nextflow.config.spec.ConfigOption
import nextflow.config.spec.ConfigScope
import nextflow.config.spec.ScopeName
import nextflow.script.dsl.Description

/**
 * The `arts` config scope.
 */
@ScopeName('arts')
@Description('''
    The `arts` scope configures the artwork generated by the nf-arts plugin.
''')
@CompileStatic
class ArtsConfig implements ConfigScope {

    static final List<String> STYLES = ['radial', 'hilbert']
    static final List<String> FORMATS = ['svg', 'png']

    @ConfigOption
    @Description('Create the artwork at the end of the run (default: `true`).')
    final boolean enabled

    @ConfigOption
    @Description('Artwork file. The extension (`.svg` or `.png`) sets the format (default: `art-<runName>.svg`).')
    final String file

    @ConfigOption
    @Description('Art style: `radial` or `hilbert` (default: `radial`).')
    final String style

    @ConfigOption
    @Description('Named color palette (default: `viridis`).')
    final String palette

    @ConfigOption
    @Description('Custom list of hex colors. Overrides `palette`.')
    final List<String> colors

    @ConfigOption
    @Description('Background hex color (default: from the palette).')
    final String background

    @ConfigOption
    @Description('Width in pixels (default: `1200`).')
    final int width

    @ConfigOption
    @Description('Height in pixels (default: `1200`).')
    final int height

    /* required by extension point -- do not remove */
    ArtsConfig() {}

    ArtsConfig(Map opts) {
        enabled = opts.enabled != null ? opts.enabled as boolean : true
        file = opts.file as String
        style = (opts.style ?: 'radial') as String
        palette = (opts.palette ?: 'viridis') as String
        colors = opts.colors as List<String>
        background = opts.background as String
        width = (opts.width != null ? opts.width : 1200) as int
        height = (opts.height != null ? opts.height : 1200) as int

        if( style !in STYLES )
            throw new IllegalArgumentException("Unknown arts.style '${style}'. Use one of: ${STYLES.join(', ')}")
        if( width < 16 || width > 10000 || height < 16 || height > 10000 )
            throw new IllegalArgumentException("arts.width and arts.height must be between 16 and 10000, got ${width}x${height}")
        if( file && format(file) !in FORMATS )
            throw new IllegalArgumentException("Unsupported arts.file extension '${file}'. Use .svg or .png")
        // fail fast on a bad palette or color, not at the end of the run
        Palette.of(palette, colors, background)
    }

    static String format(String file) {
        final dot = file.lastIndexOf('.')
        return dot < 0 ? '' : file.substring(dot + 1).toLowerCase()
    }
}
